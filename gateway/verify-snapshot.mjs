import { execFileSync } from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';

const root = import.meta.dirname;
const manifest = JSON.parse(fs.readFileSync(path.join(root, 'SNAPSHOT_MANIFEST.json'), 'utf8'));
if (manifest.format !== 1 || !Array.isArray(manifest.files) || !manifest.files.length) throw Error('Invalid snapshot manifest');
const seen = new Set();
for (const item of manifest.files) {
  if (typeof item.path !== 'string' || !/^[a-f0-9]{64}$/.test(item.sha256)) throw Error('Invalid snapshot entry');
  const relative = item.path.replaceAll('\\', '/');
  if (path.isAbsolute(relative) || relative.split('/').some(part => !part || part === '.' || part === '..') || seen.has(relative)) throw Error('Unsafe or repeated snapshot path');
  seen.add(relative);
  const filename = path.resolve(root, relative);
  if (!filename.startsWith(root + path.sep)) throw Error('Snapshot path escapes directory');
  let parent = root;
  for (const segment of relative.split('/')) {
    parent = path.join(parent, segment);
    if (fs.lstatSync(parent).isSymbolicLink()) throw Error(`Linked snapshot input: ${relative}`);
  }
  if (!fs.statSync(filename).isFile()) throw Error(`Missing snapshot file: ${relative}`);
  const bytes = fs.readFileSync(filename);
  if (bytes.length !== item.bytes || crypto.createHash('sha256').update(bytes).digest('hex') !== item.sha256) throw Error(`Snapshot mismatch: ${relative}`);
}
// A per-entry hash check proves that the listed files still match. It cannot
// see a tracked file that was never listed, so a manifest one file short still
// reports success. Ask Git for the tracked set when this really is a checkout.
// Packaged copies without a repository reason about nothing and say so instead
// of claiming completeness.
const EXCLUDED = new Set(['SNAPSHOT_MANIFEST.json', 'RUNTIME_BASELINE.json']);
let completeness = 'unavailable';
let tracked = null;
try {
  tracked = execFileSync('git', ['-c', `safe.directory=${root}`, '-C', root, 'ls-files', '-z', '--', '.'], { encoding: 'utf8' })
    .split('\0').filter(Boolean).map((entry) => entry.replaceAll('\\', '/')).filter((entry) => !EXCLUDED.has(entry));
} catch { /* Not a Git checkout, or Git is unavailable: no completeness claim. */ }
if (tracked) {
  // Compiler output is not snapshot input. It is produced by `npm run build`
  // from src/ and the lockfile, so a `dist/` entry in the index means someone
  // force-added generated bytes again and the manifest would start pinning
  // build artifacts instead of sources.
  const generated = tracked.filter((entry) => entry.startsWith('dist/'));
  if (generated.length) throw Error(`Build output is tracked again: ${generated.slice(0, 5).join(', ')}; dist/ is produced by npm run build`);
  const missing = tracked.filter((entry) => !seen.has(entry));
  if (missing.length) throw Error(`Snapshot manifest omits ${missing.length} tracked file(s): ${missing.slice(0, 5).join(', ')}`);
  const untracked = [...seen].filter((entry) => !tracked.includes(entry));
  if (untracked.length) throw Error(`Snapshot manifest lists ${untracked.length} untracked file(s): ${untracked.slice(0, 5).join(', ')}`);
  completeness = 'checked';
}
console.log(JSON.stringify({ snapshotFilesVerified: seen.size, hashesMatch: true, manifestCompleteness: completeness }));
